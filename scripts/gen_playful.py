"""Generates src/styles/playful-utilities.css — Bright & Playful overrides for Tailwind colour utilities.
Run from the project root: python3 scripts/gen_playful.py
"""
import re

P = 'html[data-style="playful"]'
INK = '#1F1A3A'

def esc(c):
    return re.sub(r'([:/.\[\]%#()])', r'\\\1', c)

BG = {
    'bg-mist-50': '#F7F4FF', 'bg-mist-50/60': 'rgba(247,244,255,.7)', 'bg-mist-50/70': 'rgba(247,244,255,.8)',
    'bg-mist-100': '#EFEAFB', 'bg-mist-200': '#E3DCF7', 'bg-mist-300': '#CFC6EE',
    'bg-ink-900': '#2B1F5C', 'bg-ink-800': '#3A2C75', 'bg-ink-950': '#24184F',
    'bg-ink-950/50': 'rgba(36,24,79,.5)', 'bg-ink-950/70': 'rgba(36,24,79,.72)', 'bg-ink-900/90': 'rgba(43,31,92,.9)', 'bg-ink-900/85': 'rgba(43,31,92,.85)',
    'bg-accent-50': '#FFF0EE', 'bg-accent-50/60': 'rgba(255,240,238,.75)', 'bg-accent-50/40': 'rgba(255,240,238,.6)', 'bg-accent-100': '#FFE0DC',
    'bg-accent-500': '#FF6B5A', 'bg-accent-600': '#FF5A4E',
    'bg-info-50': '#E6FAF7', 'bg-ok-50': '#E8FBF1', 'bg-warn-50': '#FFF6E0', 'bg-bad-50': '#FFEEF0',
}
TEXT = {
    'text-ink-950': INK, 'text-ink-900': INK, 'text-ink-800': '#2E2850', 'text-ink-700': '#463E6B',
    'text-mist-700': '#4F4870', 'text-mist-600': '#5E577F', 'text-mist-500': '#6F6890', 'text-mist-400': '#9A93B8', 'text-mist-300': '#C3BDDB',
    'text-accent-600': '#F0483C', 'text-accent-700': '#D93A2F', 'text-accent-800': '#B8322A', 'text-accent-300': '#FFB4A9',
    'text-info-700': '#0B8A7C', 'text-ink-200': '#E5DEFF', 'text-ink-300': '#CFC4FF', 'text-ink-400': '#B2A6EB',
}
BORDER = {
    'border-mist-100': '#EEE9FA', 'border-mist-200': '#E3DCF7', 'border-mist-300': '#CFC6EE', 'border-mist-400': '#B3A8DD',
    'border-accent-200': '#FFC4BD', 'border-accent-300': '#FFA39A', 'border-accent-400': '#FF8A7D', 'border-accent-500': '#FF5A4E', 'border-accent-600': '#FF5A4E',
    'border-ink-900': INK,
}
RING = {'ring-accent-100': '#FFD3CD', 'ring-accent-500': '#FF5A4E', 'ring-mist-200': '#E3DCF7', 'ring-ink-900': INK}
HOVER_BG = {'bg-mist-100': '#EFEAFB', 'bg-mist-50': '#F7F4FF', 'bg-accent-50/40': '#FFF0EE', 'bg-accent-100': '#FFE0DC', 'bg-ink-800': '#3A2C75', 'bg-accent-700': '#F0483C'}
HOVER_TEXT = {'text-accent-700': '#B8322A', 'text-ink-900': INK}
HOVER_BORDER = {'border-mist-300': '#CFC6EE', 'border-accent-300': '#FFA39A', 'border-accent-400': '#FF8A7D'}

out = ['/* GENERATED by scripts/gen_playful.py — do not edit by hand. */']
out += [f'{P} .{esc(c)}{{background-color:{v}}}' for c, v in BG.items()]
out += [f'{P} .{esc(c)}{{color:{v}}}' for c, v in TEXT.items()]
out += [f'{P} .{esc(c)}{{border-color:{v}}}' for c, v in BORDER.items()]
out += [f'{P} .{esc(c)}{{--tw-ring-color:{v}}}' for c, v in RING.items()]
out.append(f'{P} .divide-mist-100>:not([hidden])~:not([hidden]){{border-color:#EEE9FA}}')
for c, v in HOVER_BG.items():
    out.append(f'{P} .{esc("hover:" + c)}:hover{{background-color:{v}}}')
for c, v in HOVER_TEXT.items():
    out.append(f'{P} .{esc("hover:" + c)}:hover{{color:{v}}}')
    out.append(f'{P} .group:hover .{esc("group-hover:" + c)}{{color:{v}}}')
for c, v in HOVER_BORDER.items():
    out.append(f'{P} .{esc("hover:" + c)}:hover{{border-color:{v}}}')
out.append(f'{P} .{esc("focus:border-accent-500")}:focus,{P} .{esc("focus-within:border-accent-500")}:focus-within{{border-color:#FF5A4E}}')
open('src/styles/playful-utilities.css', 'w').write('\n'.join(out) + '\n')
print(len(out), 'rules')
